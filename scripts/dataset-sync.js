// @ts-check
/**
 * Keeps the app in step with the private dataset (khensolomon/lai, branch
 * `dataset`, folder myordbok/). Copies only code, never data:
 *
 *   search/search.mjs  → shared/search/search.mjs
 *   search/search.sql  → shared/search/search.sql  (+ generated statements.js)
 *
 * When the dataset has a build (build/myordbok.db), the schema of the public
 * sample (assets/db/seed.dev.sql) is also compared with it, so the sample
 * never drifts from the real tables.
 *
 * Dry run by default: reports what differs. --apply writes the copies.
 *
 *   node scripts/dataset-sync.js --dataset ../lai/myordbok
 *   node scripts/dataset-sync.js --dataset ../lai/myordbok --apply
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, 'shared', 'search');
const SAMPLE = join(ROOT, 'assets', 'db', 'seed.dev.sql');

/**
 * Same parser as search.mjs: named statements, `-- name:` lines.
 * @param {string} text
 * @returns {Record<string, string>}
 */
export function parseStatements(text) {
	/** @type {Record<string, string>} */
	const out = {};
	let name = null;
	/** @type {string[]} */
	let lines = [];
	for (const line of text.split('\n')) {
		const match = /^-- name: (\w+)\s*$/.exec(line);
		if (match) {
			if (name) out[name] = lines.join('\n').trim();
			name = match[1];
			lines = [];
		} else if (name && !line.startsWith('--')) {
			lines.push(line);
		}
	}
	if (name) out[name] = lines.join('\n').trim();
	return out;
}

/**
 * The statements as a JavaScript module, so the Worker, the browser and the
 * tests can use them without a loader for .sql files.
 * @param {string} sql
 * @param {string} source  Where the SQL came from, for the header.
 */
export function statementsModule(sql, source) {
	const statements = parseStatements(sql);
	if (!Object.keys(statements).length) throw new Error('search.sql holds no `-- name:` statements');
	return [
		'// Generated by scripts/dataset-sync.js from search.sql; do not edit.',
		`// Source: ${source}`,
		`export default Object.freeze(${JSON.stringify(statements, null, '\t')});`,
		'',
	].join('\n');
}

/**
 * Columns of every table: { table: "col type, col type" }.
 * @param {DatabaseSync} db
 */
function schemaOf(db) {
	/** @type {Record<string, string>} */
	const out = {};
	const tables = db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name").all();
	for (const { name } of tables) {
		const cols = db.prepare(`PRAGMA table_info(${JSON.stringify(String(name))})`).all();
		out[String(name)] = cols.map((c) => `${c.name} ${c.type}`).join(', ');
	}
	return out;
}

/**
 * Differences between the sample's tables and the real build's tables.
 * @param {string} sampleSql
 * @param {string} realDbPath
 * @returns {string[]}
 */
export function schemaDiff(sampleSql, realDbPath) {
	const sample = new DatabaseSync(':memory:');
	sample.exec(sampleSql);
	const real = new DatabaseSync(realDbPath, { readOnly: true });
	const a = schemaOf(sample);
	const b = schemaOf(real);
	sample.close();
	real.close();
	/** @type {string[]} */
	const problems = [];
	for (const table of new Set([...Object.keys(a), ...Object.keys(b)])) {
		if (!(table in a)) problems.push(`sample lacks table ${table} (${b[table]})`);
		else if (!(table in b)) problems.push(`sample has table ${table}, the build does not`);
		else if (a[table] !== b[table]) problems.push(`${table}: sample (${a[table]}) ≠ build (${b[table]})`);
	}
	return problems;
}

async function main() {
	const args = process.argv.slice(2);
	const i = args.indexOf('--dataset');
	if (i < 0 || !args[i + 1]) throw new Error('Give --dataset PATH, the myordbok/ folder of the dataset checkout');
	const dataset = resolve(args[i + 1]);
	const apply = args.includes('--apply');

	const files = {
		mjs: join(dataset, 'search', 'search.mjs'),
		sql: join(dataset, 'search', 'search.sql'),
	};
	for (const f of Object.values(files)) {
		if (!existsSync(f)) throw new Error(`${f} not found; is ${dataset} the myordbok/ folder of the dataset branch?`);
	}

	const mjs = await readFile(files.mjs, 'utf8');
	const sql = await readFile(files.sql, 'utf8');
	const generated = statementsModule(sql, 'khensolomon/lai dataset:myordbok/search/search.sql');
	const wanted = {
		'search.mjs': mjs,
		'search.sql': sql,
		'statements.js': generated,
	};

	let changed = 0;
	for (const [name, content] of Object.entries(wanted)) {
		const current = await readFile(join(TARGET, name), 'utf8').catch(() => null);
		if (current === content) continue;
		changed++;
		console.log(`${current === null ? 'new' : 'changed'}: shared/search/${name}`);
		if (apply) {
			await mkdir(TARGET, { recursive: true });
			await writeFile(join(TARGET, name), content);
		}
	}
	if (!changed) console.log('shared/search/ matches the dataset.');

	const realDb = join(dataset, 'build', 'myordbok.db');
	if (existsSync(realDb)) {
		const problems = schemaDiff(await readFile(SAMPLE, 'utf8'), realDb);
		if (problems.length) {
			console.error(`Sample schema differs from ${realDb}:\n  ${problems.join('\n  ')}`);
			console.error('Update assets/db/seed.dev.sql to the build schema.');
			process.exitCode = 1;
		} else {
			console.log('Sample schema matches the build.');
		}
	} else {
		console.log(`No ${realDb}; sample schema not compared (run scripts/db_build.py --apply in the dataset).`);
	}

	if (changed && !apply) console.log('Dry run. Re-run with --apply to write.');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	main().catch((err) => {
		console.error(`dataset-sync: ${err.message}`);
		process.exit(1);
	});
}
